"""Verify migrated image and scientific plot contracts against Python references.

Run: python tests/parity_check.py --binary target/release/scribe.exe
Full routing, pedagogy and KCP parity are outside this fixture's scope.
"""
import argparse
import binascii
from datetime import datetime, timezone
import json
from pathlib import Path
import struct
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
import zlib

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from scriptorium.models import content_hash
from scriptorium.engines.composition.media import decode_png
from scriptorium.engines.composition.visuals import scientific_svg


def fixture_png():
    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", binascii.crc32(kind + data) & 0xffffffff)
    data = (b"\0" + bytes([255, 0, 0, 0, 255, 0, 0, 0, 255])) * 2
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 3, 2, 8, 2, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(data)) + chunk(b"IEND", b"")


def geometry(svg):
    line = ET.fromstring(svg).find("{http://www.w3.org/2000/svg}polyline")
    assert line is not None
    points = [tuple(map(float, p.split(","))) for p in line.attrib["points"].split()]
    xs, ys = [p[0] for p in points], [p[1] for p in points]
    return [((x-min(xs))/(max(xs)-min(xs)), (max(ys)-y)/(max(ys)-min(ys))) for x,y in points]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=ROOT / "docs/rust-migration-parity.json")
    args = parser.parse_args()
    binary = args.binary.resolve(strict=True)
    checks = []
    def invoke(*argv, fail=False):
        result = subprocess.run([str(binary), *map(str, argv)], capture_output=True, text=True, encoding="utf-8")
        if fail:
            assert result.returncode != 0, f"unexpected success: {argv}"
            return
        assert result.returncode == 0, f"{argv}: {result.stderr}"
        return json.loads(result.stdout)
    with tempfile.TemporaryDirectory(prefix="scriptorium-parity-") as temp:
        vault = Path(temp)
        source = vault / "input.png"
        raw = fixture_png()
        source.write_bytes(raw)
        dimensions = decode_png(raw)
        provenance = vault / "provenance.json"
        provenance.write_text(json.dumps({"source_page":"original parity fixture", "image_url":"", "creator":"Scriptorium parity harness", "license":"CC0", "permission_basis":"Original RGB byte fixture generated by this test", "relevance":"Verify lossless image import", "original_filename":"input.png", "retrieved_at":1}), encoding="utf-8")
        flags = ("--vault", vault, "--note", "chapter.md")
        imports = ("assets", "import", *flags, "--file", source, "--mime", "image/png", "--provenance", provenance)
        record = invoke(*imports)
        assert record["sha256"] == content_hash(raw)
        assert (record["width"],record["height"]) == (dimensions["width"],dimensions["height"])
        assert (vault / record["local_path"]).read_bytes() == raw
        checks.append("Python and Rust agree on PNG dimensions and SHA-256 of unchanged asset bytes")
        assert invoke(*imports)["local_path"] == record["local_path"]
        checks.append("Identical imported bytes deduplicate to the same path")
        record_file = vault / "record.json"
        record_file.write_text(json.dumps(record), encoding="utf-8")
        invoke("assets", "verify", *flags, "--record", record_file)
        (vault / record["local_path"]).write_bytes(b"altered")
        invoke("assets", "verify", *flags, "--record", record_file, fail=True)
        checks.append("Tampered stored image is rejected")
        source.write_bytes(raw[:20])
        invoke(*imports, fail=True)
        checks.append("Truncated image is rejected")
        points = [(float(x),float(x*x)) for x in range(-3,4)]
        spec = {"renderer":"scientific", "objective":"Inspect quadratic curvature", "xlabel":"x", "ylabel":"x squared", "units":"dimensionless", "interpretation":"The minimum is at zero", "equation":"x^2", "data":{"quadratic":points}}
        spec_file = vault / "plot.json"
        spec_file.write_text(json.dumps(spec), encoding="utf-8")
        plotted = invoke("assets", "render", *flags, "--spec", spec_file)
        old_svg = scientific_svg({"quadratic":points}, title=spec["objective"], xlabel="x", ylabel="x squared")
        new_svg = (vault / plotted["local_path"]).read_text(encoding="utf-8")
        expected, actual = geometry(old_svg), geometry(new_svg)
        assert len(expected) == len(actual)
        assert all(abs(a-b)<1e-5 for old,new in zip(expected,actual) for a,b in zip(old,new))
        assert plotted["sha256"] == content_hash(new_svg)
        checks.append("Python and Rust plots preserve the same normalized numerical geometry")
        again = invoke("assets", "render", *flags, "--spec", spec_file)
        assert again["sha256"] == plotted["sha256"]
        checks.append("Scientific rendering is deterministic across repeated execution")
        spec["data"]["quadratic"][0] = [-3.0,10.0]
        spec_file.write_text(json.dumps(spec), encoding="utf-8")
        invoke("assets", "render", *flags, "--spec", spec_file, fail=True)
        checks.append("Series inconsistent with declared equation is rejected")
    report = {"captured_at":datetime.now(timezone.utc).isoformat(), "binary":str(binary), "result":"passed", "checks":checks, "scope":"Raster hash/dimensions/storage and scientific plot numerical geometry only; full CLI, KCP and pedagogy parity remain pending."}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report,indent=2)+"\n", encoding="utf-8")
    print(json.dumps(report,indent=2))


if __name__ == "__main__":
    main()
